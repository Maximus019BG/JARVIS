// Copies tui/install.sh into a TypeScript module the app can import.
//
// Embedded rather than read from disk at request time: install.sh lives in a sibling
// workspace package, and a runtime `fs` read of a path outside web/ is not traced into a
// serverless bundle — it works locally and 404s in production, which is the worst shape of
// bug to find. A module import is traced by construction.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "..", "..", "tui", "install.sh");
const target = join(here, "..", "src", "app", "install.sh", "script.generated.ts");

let script;
try {
  script = readFileSync(source, "utf8");
} catch {
  // A checkout of web/ alone still has to build. The route reports this rather than serving
  // a script that would fail halfway through an install.
  console.warn(`embed-install-sh: ${source} not found — serving a stub`);
  script = "#!/bin/sh\necho 'install.sh was not bundled with this deployment' >&2\nexit 1\n";
}

mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// Generated by scripts/embed-install-sh.mjs from tui/install.sh. Do not edit.\n` +
    `export const INSTALL_SH = ${JSON.stringify(script)};\n`,
);
console.log(`embed-install-sh: wrote ${target} (${script.length} bytes)`);
